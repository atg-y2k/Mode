function settingTags(s: Setting): string[] {
  return s === 'both' ? ['indoor', 'outdoor'] : [s];
}

export const DECOR: AssetDef[] = ENTRIES.map((e) => {
  const base = {
    id: e.id,
    name: e.name,
    category: e.category,
    subcategory: e.subcategory,
    art: { kind: 'decor', ...e.art } satisfies DecorArt,
    tags: [...e.tags, ...settingTags(e.setting)],
    description: e.description,
    cost: { low: e.cost[0], high: e.cost[1], unit: 'each' as const },
  };
  return 'heightFt' in e.size
    ? builtinAsset({ ...base, realHeightFt: e.size.heightFt })
    : builtinAsset({ ...base, realWidthFt: e.size.widthFt });
});
